"""Build the surprise-aware FOMC benchmark.

The action-only benchmark asks "what did the Fed do?". This builder asks the
question the event-study literature actually cares about: "how far was the
decision/guidance from what was priced?".

Surprise source: Bu, Rogers & Wu (2021), JME 118:331-349, extended series
(`brw_ext`), in percentage points; multiplied by 100 to get basis points.
Positive = rates higher than expected (hawkish), negative = dovish.

For each FOMC statement event:
- direction becomes the SURPRISE direction (a hike that was less hawkish than
  expected becomes an easing event, and vice versa);
- magnitude and surprise become |surprise| in bps;
- events with |surprise| < threshold are dropped (no directional test).

The output is deliberately a separate dataset (`fomc_surprise`) so the
action-only negative result stays reproducible.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

THRESHOLD_BP = 2.0


def main() -> None:
    source = ROOT / "backend" / "data" / "events" / "fomc_generated.yaml"
    surprises_path = ROOT / "backend" / "data" / "fomc" / "brw_surprises.csv"
    output = ROOT / "backend" / "data" / "events" / "fomc_surprise.yaml"

    events = yaml.safe_load(source.read_text(encoding="utf-8"))["events"]
    frame = pd.read_csv(surprises_path)
    frame["date"] = pd.to_datetime(frame["date"])
    by_date = frame.set_index("date")["brw_ext"]

    generated = []
    dropped = []
    for event in events:
        day = pd.Timestamp(event["date"])
        if day not in by_date.index:
            dropped.append((event["date"], "no surprise observation"))
            continue
        surprise_bp = float(by_date.loc[day]) * 100.0
        if abs(surprise_bp) < THRESHOLD_BP:
            dropped.append((event["date"], f"|surprise|={abs(surprise_bp):.2f}bp < {THRESHOLD_BP}"))
            continue
        action = event["direction"]
        direction = "tightening" if surprise_bp > 0 else "easing"
        updated = dict(event)
        updated["id"] = event["id"].replace("fomc-stmt-", "fomc-surprise-")
        updated["direction"] = direction
        updated["gold_direction"] = direction
        updated["magnitude"] = {"value": round(abs(surprise_bp), 2), "unit": "bps"}
        updated["surprise"] = {
            "value": round(abs(surprise_bp), 2),
            "unit": "bps",
            "sign": "positive",
            "raw": f"BRW daily surprise {surprise_bp:+.2f}bp",
        }
        updated["summary"] = (
            f"{event.get('summary', '').strip()} "
            f"Policy surprise vs expectations: {surprise_bp:+.1f}bp "
            f"(Bu-Rogers-Wu daily series; action was {action})."
        ).strip()
        tags = list(event.get("tags", []))
        for tag in ("surprise_aware", "brw"):
            if tag not in tags:
                tags.append(tag)
        updated["tags"] = tags
        generated.append(updated)

    payload = {
        "version": 1,
        "notes": [
            "Generated by scripts/build_fomc_surprise_events.py.",
            "Direction is the sign of the Bu-Rogers-Wu (2021) daily policy surprise, not the policy action.",
            "Positive surprise = hawkish (rates higher than expected); negative = dovish.",
            f"Events with |surprise| < {THRESHOLD_BP}bp are excluded.",
            "Surprise values are in basis points; source series is in percentage points.",
        ],
        "events": generated,
    }
    output.write_text(
        "# Generated file. Do not edit by hand; run scripts/build_fomc_surprise_events.py.\n"
        + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(f"wrote {len(generated)} surprise-aware events to {output}")
    print(f"dropped {len(dropped)} events (small/no surprise)")
    for date, reason in dropped[:8]:
        print("  dropped", date, reason)
    print("first rows:")
    for event in generated[:5]:
        print(
            " ",
            event["date"],
            event["direction"],
            event["magnitude"]["value"],
            "bp",
            "|",
            event["headline"],
        )


if __name__ == "__main__":
    main()
